"""Stage 1, lambda search: pick (LAMBDA_V, LAMBDA_A) from the inner runs (ARM = s1, PHASE = inner, FOLD = 0, SEED = 0).

Each inner run trained on fold 0's training actors minus a held-out 15% of them and scored those held-out actors.
Criterion, fixed before the runs: Spearman between the normalised entropy of the AV prediction, H(q_AV) / log 6,
and the AV raters' normalised vote entropy, on the held-out actors. The outer folds play no part. The table also
reports, for information only, the AUROC for the top quarter of AV disagreement, the AV cross-entropy to the votes,
and the same Spearman for the V and A readings against their own raters.

Each run is checked first: training finished (state.json) and every held-out clip scored under AV, V and A.

Usage (from the repository root):
    python analysis/stage1_select_lambda.py --runs results/stage1 --out results/stage1_lambda
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

from cremad_human import counts
from preprocess_cremad import LABELS, clip_table
from rq3_analysis import N_BOOT, Bootstrap, softmax
from rq_analysis import auroc, markdown, spearman

K = len(LABELS)
NAME = re.compile(r"stage1_s1_f0_s0_inner_v(?P<v>[\d.]+)_a(?P<a>[\d.]+)$")


def norm_entropy(p: np.ndarray) -> np.ndarray:
    return -np.sum(np.where(p > 0, p * np.log(np.where(p > 0, p, 1)), 0), 1) / np.log(K)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--runs", type=Path, default=Path("results/stage1"))
    parser.add_argument("--out", type=Path, default=Path("results/stage1_lambda"))
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    df = clip_table().set_index("uid")
    H = {c: counts(df, k) for c, k in (("AV", "av"), ("V", "v"), ("A", "a"))}
    P = {c: h / np.clip(h.sum(1, keepdims=True), 1, None) for c, h in H.items()}
    pos = {u: i for i, u in enumerate(df.index)}

    rows, checks = [], []
    for run in sorted(p for p in args.runs.iterdir() if NAME.match(p.name)):
        m = NAME.match(run.name)
        state = json.loads((run / "state.json").read_text()) if (run / "state.json").exists() else {}
        s = pd.DataFrame([json.loads(l) for l in open(run / "scores.jsonl", encoding="utf-8") if l.strip()])
        s = s[s.get("error", pd.Series(index=s.index, dtype=object)).isna()]
        n_by = s.groupby("condition")["uid"].nunique().to_dict()
        expected = state.get("sizes", [None, None])[1]
        complete = bool(state.get("train_done")) and all(n_by.get(c) == expected for c in ("AV", "V", "A"))
        checks.append({"run": run.name, "train_done": state.get("train_done"), "expected clips": expected,
                       **{f"scored {c}": n_by.get(c, 0) for c in ("AV", "V", "A")}, "OOM in training": state.get("oom"),
                       "complete": complete})
        if not complete:
            continue
        row = {"lambda_V": float(m["v"]), "lambda_A": float(m["a"])}
        for c in ("AV", "V", "A"):
            part = s[s.condition == c].set_index("uid")
            idx = np.array([pos[u] for u in part.index])
            q = softmax(part[[f"logit_{l}" for l in LABELS]].to_numpy(float))
            u, h = norm_entropy(q), norm_entropy(P[c][idx])
            if c == "AV":
                boot = Bootstrap(df.video_id.to_numpy()[idx], N_BOOT)
                high = h >= np.quantile(h, 0.75)
                row["Spearman(U_AV, A_AV) [criterion]"] = boot(lambda i: spearman(u[i], h[i]))
                row["_criterion"] = spearman(u, h)
                row["AUROC top-25% AV disagreement"] = round(auroc(u, high), 3)
                row["CE(q_AV, votes)"] = round(float(-(P[c][idx] * np.log(np.clip(q, 1e-12, None))).sum(1).mean()), 4)
            else:
                row[f"Spearman(U_{c}, A_{c})"] = round(spearman(u, h), 3)
        rows.append(row)

    tables = {"run_checks": pd.DataFrame(checks)}
    if rows:
        res = pd.DataFrame(rows).sort_values("_criterion", ascending=False)
        best = res.iloc[0]
        tables["lambda_grid"] = res.drop(columns="_criterion")
        tables["selected"] = pd.DataFrame([{"lambda_V": best.lambda_V, "lambda_A": best.lambda_A,
                                            "inner-val Spearman": round(best._criterion, 3),
                                            "runs compared": len(res)}])
    lines = ["# Stage 1 lambda search (inner held-out actors of fold 0, seed 0)\n",
             "Generated by `analysis/stage1_select_lambda.py`. Criterion: Spearman between H(q_AV)/log 6 and the AV raters' "
             f"normalised vote entropy on the held-out actors. CIs: 95% bootstrap over actors ({N_BOOT} resamples).\n"]
    for name, table in tables.items():
        table.to_csv(args.out / f"{name}.csv", index=False)
        lines += [f"## {name}\n", markdown(table.astype(object).where(table.notna(), "")), ""]
    (args.out / "report.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
