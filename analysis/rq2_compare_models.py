"""RQ2 across models: Qwen2.5-Omni-7B vs MiniCPM-o 2.6, zero-shot, all 4,403 clips.

For each model and input condition: the entropy change on conflict clips (model vs humans), the
clip-level alignment of model entropy with human disagreement, distance to the human distribution
and the Neutral share. Paired differences between the two models use the same video-level bootstrap
resamples, so their intervals account for the clips being shared.

Usage (from the repository root):
    python analysis/rq2_compare_models.py --out results/rq2_compare_models
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from rq3_analysis import N_BOOT, Bootstrap, softmax, load_logits
from rq_analysis import CONDITIONS, LABELS, auroc, ent_ce, entropy, jsd, load_humans, markdown, spearman, tvd

RUNS = {"Qwen2.5-Omni-7B": "results/omni_runs/scores.jsonl", "MiniCPM-o 2.6": "results/minicpm_runs/scores.jsonl"}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=Path("results/rq2_compare_models"))
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    h = load_humans()
    H = np.stack(h.human_dist)
    conflict = h.conflict.to_numpy() == 1
    disagree = h.all_agree.to_numpy() == 0
    human_ent = h.human_entropy.to_numpy()
    neutral = LABELS.index("Neutral")
    boot = Bootstrap(h.video_id.to_numpy(), N_BOOT)

    dist = {}
    for name, path in RUNS.items():
        logits = load_logits(path)
        dist[name] = {c: softmax(logits.loc[[(u, c) for u in h.uid]].to_numpy()) for c in CONDITIONS}

    def stats(P):
        ent, pred = entropy(P), P.argmax(1)
        return {
            "entropy change on conflict": lambda i: ent[i][conflict[i]].mean() - ent[i][~conflict[i]].mean(),
            "Spearman(entropy, human entropy)": lambda i: spearman(ent[i], human_ent[i]),
            "AUROC: entropy flags disagreement": lambda i: auroc(ent[i], disagree[i]),
            "JSD to humans": lambda i: jsd(P[i], H[i]).mean(),
            "DistCE": lambda i: tvd(P[i], H[i]).mean(),
            "Neutral share, conflict minus no conflict": lambda i: (pred[i][conflict[i]] == neutral).mean()
            - (pred[i][~conflict[i]] == neutral).mean(),
        }

    human_change = lambda i: human_ent[i][conflict[i]].mean() - human_ent[i][~conflict[i]].mean()
    human_neutral = lambda i: (h.ds_label.to_numpy()[i][conflict[i]] == "Neutral").mean() - \
        (h.ds_label.to_numpy()[i][~conflict[i]] == "Neutral").mean()
    tables = {}

    rows = [{"who": "humans", "condition": "", "entropy change on conflict": boot(human_change),
             "Neutral share, conflict minus no conflict": boot(human_neutral) + " (majority label)"}]
    for name in RUNS:
        for c in CONDITIONS:
            P = dist[name][c]
            rows.append({"who": name, "condition": c, **{k: boot(f) for k, f in stats(P).items()},
                         "mean entropy": entropy(P).mean(), "mean EntCE (signed)": ent_ce(P, H).mean()})
    tables["rq2_models_by_condition"] = pd.DataFrame(rows)

    a, b = RUNS
    rows = []
    for c in CONDITIONS:
        sa, sb = stats(dist[b][c]), stats(dist[a][c])
        rows.append({"condition": c, "comparison": f"{b} minus {a}",
                     **{k: boot(lambda i, k=k: sa[k](i) - sb[k](i)) for k in sa}})
    for name in RUNS:  # how close is each model's entropy shift to the human shift (T+A+V)?
        s = stats(dist[name]["TAV"])
        rows.append({"condition": "TAV", "comparison": f"{name} minus humans",
                     "entropy change on conflict": boot(lambda i, s=s: s["entropy change on conflict"](i) - human_change(i))})
    tables["rq2_models_paired_differences"] = pd.DataFrame(rows)

    lines = ["# RQ2 across models (zero-shot, CH-SIMS v2 + EmoS, all 4,403 clips)\n",
             f"Generated by `analysis/rq2_compare_models.py`. 95% video-level bootstrap ({N_BOOT} resamples, shared).\n"]
    for name, table in tables.items():
        table.to_csv(args.out / f"{name}.csv", index=False)
        lines += [f"## {name}\n", markdown(table.astype(object).where(table.notna(), "")), ""]
    (args.out / "report.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
