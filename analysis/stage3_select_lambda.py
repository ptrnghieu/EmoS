"""Stage 3, lambda search: pick LAMBDA_AMB from the inner runs (ARM = s3, VIEW = A1, PHASE = inner, FOLD = 0, SEED = 0).

Each inner run trained on fold 0's training actors minus a held-out 15% of them and scored those held-out actors.
Criterion, fixed before the runs: Spearman between the ambiguity head's score (`amb_score`, AV reading) and the AV
raters' normalised vote entropy A^AV on the held-out actors. The outer folds play no part. Reported for information
only: the same for the entropy of q_AV, the partial Spearman given emotion x sentence, and the ranking-pair statistics.

Usage (from the repository root; downloads the CREMA-D rating files):
    python analysis/stage3_select_lambda.py --runs results/stage3 --out results/stage3_lambda
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

from cremad_human import counts
from preprocess_cremad import LABELS, clip_table
from rq3_analysis import N_BOOT, Bootstrap, softmax
from rq_analysis import markdown, spearman
from visual_probe_analysis import norm_entropy, partial_spearman

NAME = re.compile(r"stage3_s3_A1_f0_s0_inner_amb(?P<amb>[\d.]+)$")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--runs", type=Path, default=Path("results/stage3"))
    parser.add_argument("--out", type=Path, default=Path("results/stage3_lambda"))
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    df = clip_table().set_index("uid")
    AV = counts(df, "av")
    df["A_AV"] = norm_entropy(AV / np.clip(AV.sum(1, keepdims=True), 1, None))

    rows, checks = [], []
    for run in sorted(p for p in args.runs.iterdir() if NAME.match(p.name)):
        state = json.loads((run / "state.json").read_text())
        s = pd.DataFrame([json.loads(l) for l in open(run / "scores.jsonl", encoding="utf-8") if l.strip()])
        s = s[s.get("error", pd.Series(index=s.index, dtype=object)).isna()]
        av = s[s.condition == "AV"].drop_duplicates("uid", keep="last").set_index("uid")
        expected = state["sizes"][1]
        rk = state["rank"]
        complete = bool(state.get("train_done")) and len(av) == expected and av["amb_score"].notna().all()
        checks.append({"run": run.name, "train_done": state.get("train_done"), "held-out clips": expected,
                       "scored AV": len(av), "OOM": state.get("oom"), "complete": complete,
                       "ranking pairs per clip": round(rk["pairs"] / max(1, rk["clips"]), 1),
                       "clips without a pair": f"{rk['no_pair'] / max(1, rk['clips']):.1%}",
                       "sentence-level pairs used": f"{rk['sentence_level'] / max(1, rk['clips']):.1%}",
                       "dA in [.15,.25) / [.25,.4) / >=.4": " / ".join(map(str, rk["delta_bins"]))})
        if not complete:
            continue
        sub = df.loc[av.index]
        y, emo_sent = sub.A_AV.to_numpy(), (sub.intended + sub.sentence_code).to_numpy()
        amb = av["amb_score"].to_numpy(float)
        ent = norm_entropy(softmax(av[[f"logit_{l}" for l in LABELS]].to_numpy(float)))
        boot = Bootstrap(sub.video_id.to_numpy(), N_BOOT)
        rows.append({"lambda_amb": float(NAME.match(run.name)["amb"]), "_criterion": spearman(amb, y),
                     "Spearman(amb_score, A^AV) [criterion]": boot(lambda i: spearman(amb[i], y[i])),
                     "partial given emotion x sentence (amb_score)": boot(lambda i: partial_spearman(amb[i], y[i], emo_sent[i])),
                     "Spearman(U^AV entropy, A^AV)": boot(lambda i: spearman(ent[i], y[i]))})

    tables = {"run_checks": pd.DataFrame(checks)}
    if rows:
        res = pd.DataFrame(rows).sort_values("_criterion", ascending=False)
        tables["lambda_grid"] = res.drop(columns="_criterion")
        tables["selected"] = pd.DataFrame([{"lambda_amb": res.iloc[0].lambda_amb,
                                            "inner-val Spearman(amb_score, A^AV)": round(res.iloc[0]._criterion, 3),
                                            "runs compared": len(res)}])
    lines = ["# Stage 3 lambda search (inner held-out actors of fold 0, seed 0, view A1)\n",
             "Generated by `analysis/stage3_select_lambda.py`. Criterion: Spearman(amb_score, A^AV) on the held-out "
             f"actors. CIs: 95% bootstrap over actors ({N_BOOT} resamples).\n"]
    for name, table in tables.items():
        table.to_csv(args.out / f"{name}.csv", index=False)
        lines += [f"## {name}\n", markdown(table.astype(object).where(table.notna(), "")), ""]
    (args.out / "report.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
